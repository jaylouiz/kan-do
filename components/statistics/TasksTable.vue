<!--
@component TasksTable
@kind component
@category display
@description Table displaying task completion records with columns that can be re-ordered
@usage Used in statistics page to show filtered tasks
@avoid Only filtered task records on the Statistik page; board tasks are TaskCard.
@responsibility
- Display task records in table format
- Handle row clicks to open task detail modal
- Show empty state when no data available
- Keep the horizontal scroll region keyboard-focusable and named
-->

<template>
  <div>
    <p v-if="tasks.length === 0" class="py-6 text-muted">
      {{ emptyStateText ?? t('statistics.table.empty') }}
    </p>

    <UTable
      v-else
      :data="tasks"
      :columns="tableColumns"
      role="region"
      tabindex="0"
      :aria-label="t('statistics.table.scrollRegionLabel')"
      :ui="{ th: 'whitespace-nowrap' }"
      @select="handleRowSelect"
    />
  </div>
</template>

<script setup lang="ts">
import { useI18n } from 'vue-i18n';
import { useLocaleFormat } from "~/composables/useLocaleFormat";
import { getAccuracyTier, getAccuracyVerdict, getVerdictColor } from "~/utils/statisticsAccuracy";
import { computed, h } from 'vue';
import type { TableColumn, TableRow } from '@nuxt/ui';
import type { TaskCompletionRecord } from '@/store/taskStatistics';

defineOptions({ name: 'TasksTable' });

const props = withDefaults(defineProps<{
  /** Tasks to display in the table */
  tasks: TaskCompletionRecord[];
  /** Show completed date column */
  showCompletedDate?: boolean;
  /** Empty state text */
  emptyStateText?: string;
}>(), {
  showCompletedDate: true,
  emptyStateText: undefined
});

const emit = defineEmits<{
  /** Emitted when a row is clicked */
  (e: 'rowClick', record: TaskCompletionRecord): void;
}>();

/**
 * Handle row selection: UTable's `select` event (a click or Enter on the row); it has no `row-click` event, so the
 * drill-down from the task list never fired before #469
 */
const handleRowSelect = (_event: Event, row: TableRow<TaskCompletionRecord>) => {
  emit('rowClick', row.original);
};

/**
 * Format time duration
 */
const { t } = useI18n();
const { formatDuration, formatDateTime } = useLocaleFormat();
const formatTime = (seconds: number): string => formatDuration(seconds, "compact");

/**
 * Format date
 */
const formatDate = (date: Date | string): string => formatDateTime(date, "dayMonthYearTime");

/**
 * Translated label for a timebox verdict (`null` = no timebox)
 */
const getVerdictLabel = (verdict: ReturnType<typeof getAccuracyVerdict>): string =>
  t(`statistics.accuracy.${verdict ?? 'noTimebox'}`);

/** Static class map (dynamic `bg-${color}` would not be generated by Tailwind). */
const VERDICT_DOT_CLASS = { success: 'bg-success', warning: 'bg-warning', error: 'bg-error' } as const;

/**
 * Get accuracy label
 */
const getAccuracyLabel = (accuracy: number): string => {
  const tier = getAccuracyTier(accuracy);
  return t(`statistics.accuracyLabel.${tier === 'poor' ? 'needsImprovement' : tier}`);
};

/**
 * Table columns configuration
 * Using TanStack Table compatible accessorKey/id with cell render functions
 */
const tableColumns = computed<TableColumn<TaskCompletionRecord>[]>(() => {
  const columns: TableColumn<TaskCompletionRecord>[] = [
    {
      accessorKey: 'title',
      header: t('statistics.table.task'),
      cell: ({ row }) => {
        const record = row.original;
        // Topic and activity are plain text: label colours never tint chips or dots here
        const meta = [record.topic, record.activity].filter(Boolean).join(' · ');

        return h('div', { class: 'space-y-1' }, [
          h('div', { class: 'font-medium' }, record.title),
          meta ? h('div', { class: 'text-xs text-muted' }, meta) : null
        ]);
      }
    }
  ];
  
  if (props.showCompletedDate) {
    columns.push({
      accessorKey: 'completedAt',
      header: t('statistics.table.completedAt'),
      cell: ({ row }) => formatDate(row.original.completedAt)
    });
  }
  
  columns.push(
    {
      accessorKey: 'actualTimeSpentSeconds',
      header: t('statistics.table.timeSpent'),
      cell: ({ row }) => formatTime(row.original.actualTimeSpentSeconds)
    },
    {
      accessorKey: 'timeBoxSeconds',
      header: t('statistics.table.plannedTime'),
      cell: ({ row }) => row.original.timeBoxSeconds ? formatTime(row.original.timeBoxSeconds) : '—'
    },
    {
      accessorKey: 'estimationAccuracy',
      header: t('statistics.table.accuracy'),
      cell: ({ row }) => {
        const accuracy = row.original.estimationAccuracy;
        if (accuracy === null) return h('span', { class: 'text-muted' }, '—');
        return h('div', { class: 'text-right' }, [
          h('div', { class: 'font-semibold text-highlighted' }, `${Math.round(accuracy)}%`),
          h('div', { class: 'text-xs text-muted' }, getAccuracyLabel(accuracy))
        ]);
      }
    },
    {
      id: 'timeboxStatus',
      header: t('statistics.table.inTimebox'),
      cell: ({ row }) => {
        const verdict = getAccuracyVerdict(row.original);
        const color = getVerdictColor(verdict);
        return h('span', {
          class: 'inline-flex items-center gap-1.5 px-2 py-0.5 rounded-md text-xs font-medium bg-elevated text-default'
        }, [
          color === 'neutral' ? null : h('span', { class: ['size-1.5 rounded-full', VERDICT_DOT_CLASS[color]], 'aria-hidden': 'true' }),
          getVerdictLabel(verdict)
        ]);
      }
    },
    {
      accessorKey: 'isUnplanned',
      header: t('statistics.table.unplanned'),
      cell: ({ row }) => {
        if (row.original.isUnplanned) {
          return h('div', { class: 'flex justify-center' }, [
            h('span', { class: 'i-ph-warning w-5 h-5 text-warning' })
          ]);
        }
        return h('span', { class: 'text-muted flex justify-center' }, '—');
      }
    }
  );
  
  return columns;
});
</script>

<style scoped>
:deep(tbody tr) {
  cursor: pointer;
  transition: background-color 150ms ease;
}

:deep(tbody tr:hover) {
  background-color: var(--ui-bg-elevated);
}
</style>
